# 生成「病态工作区」复现仓库:一个真实 git 仓库,带海量未跟踪文件与已修改文件。
# 用途:手动验证更改栏/资源管理器在极端规模下的表现,以及跑 GitStatusPipelineBenchmark。
# 输出目录由参数决定,默认写在 $env:TEMP 下;脚本不会碰任何已存在的目录(除非它自己标记过)。
param(
    [string]$Path = (Join-Path $env:TEMP 'nornia-heavy-repo'),
    [int]$Untracked = 10000,
    [int]$Modified = 200,
    [int]$Tracked = 500,
    [int]$PerDirectory = 200,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'

function Invoke-Git {
    param([Parameter(Mandatory)][string[]]$Arguments)
    & git -C $Path @Arguments | Out-Null
    if ($LASTEXITCODE -ne 0) {
        throw "git $($Arguments -join ' ') 失败,退出码 $LASTEXITCODE"
    }
}

$marker = Join-Path $Path '.nornia-heavy-repo'
if (Test-Path $Path) {
    if (-not (Test-Path $marker)) {
        throw "$Path 已存在且不是本脚本生成的目录,拒绝改动。请换一个 -Path。"
    }
    if (-not $Force) {
        Write-Host "$Path 已就绪(需要重建请加 -Force)。"
        exit 0
    }
    Remove-Item $Path -Recurse -Force
}

New-Item -ItemType Directory -Path $Path | Out-Null
Set-Content -LiteralPath $marker -Value "generated by tools/heavy-git-repo.ps1"

Invoke-Git @('init')
Invoke-Git @('config', 'user.name', 'Nornia Fixture')
Invoke-Git @('config', 'user.email', 'fixture@nornia.local')

# 已跟踪且保持干净的文件:让 status 输出里存在大量 N... 头与无徽章行,更接近真实仓库。
$clean = 0
for ($i = 0; $i -lt $Tracked; $i++) {
    $relative = "src/clean/clean-{0:D5}.txt" -f $i
    $full = Join-Path $Path ($relative -replace '/', [IO.Path]::DirectorySeparatorChar)
    New-Item -ItemType Directory -Force -Path (Split-Path $full) | Out-Null
    Set-Content -LiteralPath $full -Value "clean $i"
    $clean++
}

# 已跟踪且被改写的文件:产生 .M 记录。
for ($i = 0; $i -lt $Modified; $i++) {
    $relative = "src/modified/modified-{0:D5}.txt" -f $i
    $full = Join-Path $Path ($relative -replace '/', [IO.Path]::DirectorySeparatorChar)
    New-Item -ItemType Directory -Force -Path (Split-Path $full) | Out-Null
    Set-Content -LiteralPath $full -Value "original"
}

Invoke-Git @('add', 'src')
Invoke-Git @('commit', '-m', 'fixture baseline')

for ($i = 0; $i -lt $Modified; $i++) {
    $full = Join-Path $Path ('src/modified/modified-{0:D5}.txt' -f $i)
    Set-Content -LiteralPath $full -Value "changed $i"
}

# 未跟踪文件:porcelain v2 会为每个文件生成一条 ?? 记录,这是旧实现卡顿的主因。
$directoryIndex = 0
for ($i = 0; $i -lt $Untracked; $i++) {
    if ($i % $PerDirectory -eq 0) { $directoryIndex++ }
    $relative = "untracked/d{0:D4}/file-{1:D6}.txt" -f $directoryIndex, $i
    $full = Join-Path $Path ($relative -replace '/', [IO.Path]::DirectorySeparatorChar)
    $parent = Split-Path $full
    if (-not (Test-Path $parent)) { New-Item -ItemType Directory -Force -Path $parent | Out-Null }
    Set-Content -LiteralPath $full -Value "u"
}

# 记录数按 Nornia 实际使用的开关统计(--untracked-files=all -z):默认的目录折叠会把一万条
# 未跟踪显示成三行,那样就复现不出「更改栏被撑爆」的形态。
$raw = & git -C $Path status --porcelain=v2 --branch -z --untracked-files=all | Out-String
$records = (($raw -split "`0") | Where-Object { $_.Trim() -ne '' }).Count
Write-Host ("病态仓库已生成: {0}" -f $Path)
Write-Host ("  未跟踪 {0} / 已修改 {1} / 干净已跟踪 {2}" -f $Untracked, $Modified, $clean)
Write-Host ("  porcelain 记录数(-uall): {0}" -f $records)
